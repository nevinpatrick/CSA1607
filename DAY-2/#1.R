A <- c(18, 2, 20)
B <- c(22, 28, 10)
C <- c(20, 40, 40)
preferences <- data.frame(A, B, C)
cat("Covariance between B and C:\n")
print(cov(B, C))
cat("\nCovariance Matrix:\n")
print(cov(preferences))
cat("\nCorrelation between B and C:\n")
print(cor(B, C))
cat("\nCorrelation Matrix:\n")
print(cor(preferences))
